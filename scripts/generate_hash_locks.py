"""Generate hash-pinned requirement locks from exact version pins.

The Docker build consumes the generated ``requirements-runtime.lock`` and
``requirements-dev.lock`` files with pip's hash-checking mode. This script uses
PyPI's JSON metadata API, so it does not need to download every artifact just
to learn its SHA-256 digest.

Usage inside the Docker test image:

    python3 scripts/generate_hash_locks.py .runtime-freeze.tmp requirements-runtime.lock
    python3 scripts/generate_hash_locks.py .dev-freeze.tmp requirements-dev.lock
"""

from __future__ import annotations

import json
import re
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from urllib.parse import quote

USER_AGENT = "mcp-github-projects-lock-generator/1.0"


def normalize_name(name: str) -> str:
    """Return the PEP 503 normalized project name used by PyPI URLs."""
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> list[tuple[str, str]]:
    """Read exact ``name==version`` pins, ignoring comments and blank lines."""
    pins: list[tuple[str, str]] = []
    for line_number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if "==" not in line:
            raise ValueError(f"{path}:{line_number}: expected an exact name==version pin: {line!r}")
        name, version = line.split("==", 1)
        name = name.strip()
        version = version.strip().split(";", 1)[0].strip()
        if not name or not version:
            raise ValueError(f"{path}:{line_number}: malformed pin: {line!r}")
        pins.append((name, version))
    if not pins:
        raise ValueError(f"{path}: no exact pins found")
    return sorted(dict.fromkeys(pins), key=lambda item: item[0].lower())


def pypi_hashes(name: str, version: str, *, retries: int = 3) -> list[str]:
    """Return every published SHA-256 artifact hash for one exact release."""
    normalized = normalize_name(name)
    url = f"https://pypi.org/pypi/{quote(normalized)}/{quote(version)}/json"
    last_error: Exception | None = None
    for attempt in range(retries):
        try:
            request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(request, timeout=20) as response:  # nosec B310 - fixed https://pypi.org release-metadata URL
                payload = json.loads(response.read().decode("utf-8"))
            hashes = sorted({
                item["digests"]["sha256"]
                for item in payload.get("urls", [])
                if isinstance(item.get("digests"), dict) and item["digests"].get("sha256")
            })
            if not hashes:
                raise ValueError(f"{name}=={version}: PyPI returned no artifact hashes")
            return hashes
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError, ValueError) as exc:
            last_error = exc
            if attempt + 1 < retries:
                time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"failed to fetch hashes for {name}=={version}: {last_error}")


def render_lock(pins: list[tuple[str, str]], artifacts: dict[tuple[str, str], list[str]], source: str) -> str:
    """Render a pip requirements file in hash-checking format."""
    lines = [
        "# Generated by scripts/generate_hash_locks.py; do not edit by hand.",
        f"# Source pins: {source}. Regenerate through the documented Docker lock target.",
        "",
    ]
    for name, version in pins:
        hashes = artifacts[(name, version)]
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            suffix = " \\" if index + 1 < len(hashes) else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Generate one hash-pinned lock file."""
    if len(argv) != 3:
        print("usage: generate_hash_locks.py <exact-pin-file> <output-lock>", file=sys.stderr)
        return 2
    source = Path(argv[1])
    output = Path(argv[2])
    pins = read_pins(source)
    artifacts: dict[tuple[str, str], list[str]] = {}
    failures: list[str] = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        futures = {pool.submit(pypi_hashes, name, version): (name, version) for name, version in pins}
        for future in as_completed(futures):
            pin = futures[future]
            try:
                artifacts[pin] = future.result()
            except Exception as exc:  # collect all failures before failing the run
                failures.append(str(exc))
    if failures:
        for failure in failures:
            print(failure, file=sys.stderr)
        return 1
    output.write_text(render_lock(pins, artifacts, str(source)), encoding="utf-8")
    print(f"wrote {output} with {len(pins)} hash-pinned packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
